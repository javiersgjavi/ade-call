// To add a language, add its dictionary here under its primary subtag.
export const dictionaries: Record<string, Dictionary> = { en, es };
export const DEFAULT_LANGUAGE = 'en';

let current = DEFAULT_LANGUAGE, currentLocale = DEFAULT_LANGUAGE;
/** The selected interface language (a key of `dictionaries`). */
export function language() { return current; }
/** The browser tag that selected it (e.g. es-MX), for dates and times. */
export function locale() { return currentLocale; }

/** First preferred tag whose primary subtag has a dictionary; English otherwise. */
export function pickLanguage(preferred: readonly (string | undefined | null)[]): { language: string; locale: string } {
  for (const tag of preferred) {
    const primary = tag?.split(/[-_]/)[0].toLowerCase();
    if (primary && Object.hasOwn(dictionaries, primary)) {
      try { return { language: primary, locale: Intl.getCanonicalLocales(tag!.replace(/_/g, '-'))[0] }; } catch { return { language: primary, locale: primary }; }
    }
  }
  return { language: DEFAULT_LANGUAGE, locale: DEFAULT_LANGUAGE };
}

export function setLanguage(choice: { language: string; locale?: string }) {
  current = Object.hasOwn(dictionaries, choice.language) ? choice.language : DEFAULT_LANGUAGE;
  currentLocale = current === choice.language ? choice.locale || current : current;
}

export function isMessageKey(key: string): key is MessageKey { return Object.hasOwn(en, key); }

/** Text for `key` in the selected language with {placeholder} values filled in. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  const text = dictionaries[current]?.[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(vars, name) ? String(vars[name]) : match);
}

// Static markup keeps its English text and names the key in these attributes.
const STATIC: [string, string | null][] = [['data-i18n', null], ['data-i18n-aria-label', 'aria-label'], ['data-i18n-title', 'title']];
interface Translatable { getAttribute(name: string): string | null; setAttribute(name: string, value: string): void; textContent: string | null }
interface Page { documentElement: { lang: string }; querySelectorAll(selector: string): Iterable<Translatable> }

export function translatePage(page: Page) {
  page.documentElement.lang = current;
  for (const [source, target] of STATIC) {
    for (const node of page.querySelectorAll(`[${source}]`)) {
      const key = node.getAttribute(source) || '';
      if (!isMessageKey(key)) continue;
      if (target) node.setAttribute(target, t(key)); else node.textContent = t(key);
    }
  }
}

type Browser = { languages?: readonly string[]; language?: string };
/** Selects the language and translates the page: the stored choice of this browser if it
 * has a dictionary ('auto' or nothing means the browser preferences), English otherwise. */
export function localize(browser: Browser, page?: Page, preference = 'auto') {
  setLanguage(Object.hasOwn(dictionaries, preference) ? { language: preference, locale: preference } : pickLanguage([...(browser.languages || []), browser.language]));
  if (page) translatePage(page);
  return current;
}

// The language chosen in Settings, per browser. Storage may be unavailable (private mode).
export const PREFERENCE_KEY = 'ui-language';
export function storedPreference(storage?: Pick<Storage, 'getItem'>) {
  try { const value = storage?.getItem(PREFERENCE_KEY); return value && Object.hasOwn(dictionaries, value) ? value : 'auto'; } catch { return 'auto'; }
}
export function storePreference(value: string, storage?: Pick<Storage, 'setItem' | 'removeItem'>) {
  try { if (Object.hasOwn(dictionaries, value)) storage?.setItem(PREFERENCE_KEY, value); else storage?.removeItem(PREFERENCE_KEY); } catch { /* Only this browser's convenience. */ }
}
/** Language hints for the voice's greeting: an explicit choice first, then the browser's. */
export function voiceLanguages(browser: Browser, preference = 'auto') {
  const tags = [...(Object.hasOwn(dictionaries, preference) ? [preference] : []), ...(browser.languages || []), ...(browser.language ? [browser.language] : [])];
  return [...new Set(tags)].slice(0, 5);
}

